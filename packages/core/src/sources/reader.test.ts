import { readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { unzipSync, zipSync } from "fflate";
import { describe, expect, it } from "vitest";
import { prepareConvertRequest } from "../archive/zip.js";
import { readFixture } from "../test-helpers.js";
import { findSourceReader, SOURCE_READERS } from "./index.js";

const text = (s: string) => new TextEncoder().encode(s);
const sourcesDir = fileURLToPath(new URL("../test-fixtures/sources/", import.meta.url));

describe("source readers", () => {
  it("has the Bambu Studio family first, and every reader names its format", () => {
    expect(SOURCE_READERS.map((r) => r.format)).toEqual(["bambu-family"]);
  });

  it("recognizes every committed source fixture as the Bambu Studio family, by its project_settings.config", () => {
    for (const name of readdirSync(sourcesDir).filter((f) => f.endsWith(".3mf"))) {
      const entries = unzipSync(readFixture(`sources/${name}`));
      expect(findSourceReader(entries)?.format, name).toBe("bambu-family");
      expect(prepareConvertRequest(readFixture(`sources/${name}`)).source, name).toBe("bambu-family");
    }
  });

  it("recognizes nothing in a zip without project settings, so the generic refusals apply", () => {
    expect(findSourceReader({ "3D/3dmodel.model": text("<model/>") })).toBeNull();
    expect(findSourceReader({ "part.stl": text("solid x") })).toBeNull();
    expect(findSourceReader({ "Metadata/Slic3r_PE.config": text("; generated by PrusaSlicer 2.9.1\n") })).toBeNull();
    expect(() => prepareConvertRequest(zipSync({ "3D/3dmodel.model": text("<model/>") }))).toThrow(/holds only the model/);
    expect(() => prepareConvertRequest(zipSync({ "Metadata/Slic3r_PE.config": text("; generated by PrusaSlicer 2.9.1\n") }))).toThrow(expect.objectContaining({ code: "unsupported_slicer" }));
  });

  it("reads the same request through the reader as prepareConvertRequest gives", () => {
    const bytes = readFixture("synthetic-demo.3mf");
    const entries = unzipSync(bytes);
    const reader = findSourceReader(entries)!;
    const direct = reader.read(entries, { unpackedBytes: 0, warnings: [] });
    const whole = prepareConvertRequest(bytes);
    expect(direct.request).toEqual(whole.request);
    expect(direct.source).toBe(whole.source);
  });
});
