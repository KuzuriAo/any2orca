import { readFileSync } from "node:fs";
import { unzipSync } from "fflate";
import { describe, expect, it } from "vitest";
import { parsePrusaIni, splitNumberList, splitStringList, unescapeValue } from "./ini.js";

const fixture = () => {
  const bytes = new Uint8Array(readFileSync(new URL("../../test-fixtures/prusaslicer/prusaslicer-2.9.6.3mf", import.meta.url)));
  return new TextDecoder().decode(unzipSync(bytes)["Metadata/Slic3r_PE.config"]);
};

describe("the PrusaSlicer config file", () => {
  it("reads the real 2.9.6 fixture: the slicer, its version and every key", () => {
    const ini = parsePrusaIni(fixture());
    expect(ini.slicer).toBe("PrusaSlicer");
    expect(ini.version).toBe("2.9.6");
    expect(ini.settings.size).toBe(376);
    expect(ini.settings.get("printer_model")).toBe("COREONE");
    expect(ini.settings.get("print_settings_id")).toBe("0.20mm BALANCED @COREONE HF0.4");
    // Written in quotes by PrusaSlicer, read back without them.
    expect(ini.settings.get("filament_settings_id")).toBe("Generic ABS @COREONE HF0.4");
    expect(ini.settings.get("layer_height")).toBe("0.2");
    expect(ini.settings.get("bed_shape")).toBe("0x0,250x0,250x220,0x220");
    // A G-code block keeps its newlines.
    expect(ini.settings.get("start_gcode")).toContain("\n");
  });

  it("unescapes the way PrusaSlicer wrote it, quoted or not, and leaves bare values alone", () => {
    expect(unescapeValue('"Generic PLA @MK4"')).toBe("Generic PLA @MK4");
    expect(unescapeValue('"a \\"quoted\\" word\\nnext line\\\\"')).toBe('a "quoted" word\nnext line\\');
    expect(unescapeValue("M17 ; enable steppers\\nM862.1 P[nozzle_diameter]")).toBe("M17 ; enable steppers\nM862.1 P[nozzle_diameter]");
    expect(unescapeValue("0.2")).toBe("0.2");
    expect(unescapeValue('"')).toBe('"');
    expect(unescapeValue('"unterminated')).toBe('"unterminated');
  });

  it("splits a list of numbers on commas, and a list of strings on semicolons outside quotes", () => {
    expect(splitNumberList("0.4,0.4,0.6")).toEqual(["0.4", "0.4", "0.6"]);
    expect(splitNumberList("#FFF2EC")).toEqual(["#FFF2EC"]);
    expect(splitStringList('"Generic ABS @COREONE HF0.4"')).toEqual(["Generic ABS @COREONE HF0.4"]);
    expect(splitStringList('"Prusament PLA @MK4";"Generic PETG; special"')).toEqual(["Prusament PLA @MK4", "Generic PETG; special"]);
    expect(splitStringList("#FFF2EC;#000000")).toEqual(["#FFF2EC", "#000000"]);
    expect(splitStringList("")).toEqual([""]);
    expect(splitStringList('"a \\"q\\" b";c')).toEqual(['a "q" b', "c"]);
  });

  it("ignores what isn't a setting line, keeps the last repeated value, and caps the lines read", () => {
    const ini = parsePrusaIni(["; generated by SuperSlicer 2.5.59 on 2024-01-01", "garbage", "; not a key", "; a_key = 1", "; a_key = 2", "; Bad-Key = 3", "; x = y = z"].join("\n"));
    expect(ini.slicer).toBe("SuperSlicer");
    expect(ini.version).toBe("2.5.59");
    expect([...ini.settings]).toEqual([
      ["a_key", "2"],
      ["x", "y = z"],
    ]);
    const huge = Array.from({ length: 6000 }, (_, i) => `; k${i} = ${i}`).join("\n");
    expect(parsePrusaIni(huge).settings.size).toBe(5000);
    expect(parsePrusaIni("").slicer).toBeNull();
  });
});
