import { readFileSync } from "node:fs";
import { unzipSync } from "fflate";
import { describe, expect, it } from "vitest";
import { SETTINGS_CATALOG } from "../../diff/settingsCatalog.js";
import { convertObjectOverrides, convertPrusaSettings } from "./convertSettings.js";
import { parsePrusaIni } from "./ini.js";

const fixtureIni = () => {
  const bytes = new Uint8Array(readFileSync(new URL("../../test-fixtures/prusaslicer/prusaslicer-2.9.6.3mf", import.meta.url)));
  return parsePrusaIni(new TextDecoder().decode(unzipSync(bytes)["Metadata/Slic3r_PE.config"]));
};

const ini = (lines: string[]) => parsePrusaIni(["; generated by PrusaSlicer 2.9.6 on 2026-10-31", ...lines.map((l) => `; ${l}`)].join("\n"));

describe("converting PrusaSlicer settings to Snapmaker Orca's", () => {
  it("converts the 2.9.6 fixture: renames, shapes, and the policy that everything mapped counts as changed", () => {
    const { settings, dropped, unknown, warnings } = convertPrusaSettings(fixtureIni());
    expect(unknown).toEqual([]);
    expect(settings.wall_loops).toBe("2");
    expect(settings.sparse_infill_density).toBe("15%");
    expect(settings.sparse_infill_pattern).toBe("grid");
    expect(settings.top_surface_pattern).toBe("monotonicline");
    expect(settings.initial_layer_print_height).toBe("0.2");
    expect(settings.outer_wall_speed).toBe("200");
    expect(settings.inner_wall_speed).toBe("150");
    // Per-filament and per-extruder values become lists, single ones stay single.
    expect(settings.nozzle_temperature).toEqual(["260"]);
    expect(settings.textured_plate_temp).toEqual(["110"]);
    expect(settings.hot_plate_temp_initial_layer).toEqual(["110"]);
    expect(settings.filament_settings_id).toEqual(["Generic ABS @COREONE HF0.4"]);
    expect(settings.filament_colour).toEqual(["#FFF2EC"]);
    expect(settings.filament_type).toEqual(["ABS"]);
    expect(settings.filament_vendor).toEqual(["Generic"]);
    expect(settings.nozzle_diameter).toEqual(["0.4"]);
    // A print setting Snapmaker Orca keeps per hotend type is still written as one value; the pipeline spreads it.
    expect(settings.travel_speed).toBe("350");
    expect(settings.layer_height).toBe("0.2");
    // PrusaSlicer's 0.22% shrinkage is Snapmaker Orca's 99.78% scale.
    expect(settings.filament_shrink).toEqual(["99.78%"]);
    expect(settings.filament_shrinkage_compensation_z).toEqual(["99.78%"]);
    // Flags folded into modes.
    expect(settings.support_type).toBe("normal(manual)");
    expect(settings.support_style).toBe("snug");
    expect(settings.enable_support).toBe("1");
    expect(settings.seam_slope_type).toBe("none");
    expect(settings.ironing_type).toBe("no ironing");
    expect(settings.gap_fill_target).toBe("everywhere");
    expect(settings.print_sequence).toBe("by layer");
    expect(settings.wall_sequence).toBe("inner wall/outer wall");
    expect(settings.enable_arc_fitting).toBe("1");
    expect(settings.ensure_vertical_shell_thickness).toBe("ensure_all");
    expect(settings.z_hop_types).toEqual(["Slope Lift"]);
    // Snapmaker Orca's resolution is the G-code one (PrusaSlicer's own "resolution" is its slice resolution, dropped).
    expect(settings.resolution).toBe("0.008");
    // 80% of the 0.45 mm outer wall line.
    expect(settings.support_object_xy_distance).toBe("0.36");
    expect(settings.support_bottom_z_distance).toBe("0.2");
    // Overhang speed bands, reversed.
    expect(settings.overhang_4_4_speed).toBe("15");
    expect(settings.overhang_1_4_speed).toBe("70%");
    // A filament override left to the printer (`nil`) isn't carried; the printer's own value is.
    expect(settings.filament_retraction_length).toBeUndefined();
    expect(settings.retraction_length).toEqual(["0.7"]);
    // The U1's own stay out: bed shape, G-code, motion limits.
    // The source bed is carried for the inspection only; the pipeline never transfers it.
    expect(settings.printable_area).toEqual(["0x0", "250x0", "250x220", "0x220"]);
    expect(settings.printable_height).toBe("270");
    for (const key of ["bed_shape", "machine_start_gcode", "start_gcode", "machine_max_speed_x", "gcode_flavor", "thumbnails"]) {
      expect(settings[key]).toBeUndefined();
    }
    expect(settings.version).toBe("2.9.6");
    expect(dropped.map((d) => d.key)).toEqual(expect.arrayContaining(["extra_perimeters", "post_process", "enable_dynamic_fan_speeds", "max_print_speed"]));
    expect(warnings).toEqual([]);
    // Every filament and machine list is a list, every print setting one value (this project has one filament).
    for (const [key, value] of Object.entries(settings)) {
      const info = SETTINGS_CATALOG[key];
      if (!info?.type || key === "different_settings_to_system") continue;
      expect(Array.isArray(value), key).toBe(info.type.endsWith("s") && info.group !== "print");
    }
    const [printEntry, ...rest] = settings.different_settings_to_system as string[];
    expect(rest).toEqual(["", ""]);
    const listed = printEntry.split(";");
    expect(listed).toContain("wall_loops");
    expect(listed).not.toContain("nozzle_temperature");
    // Machine settings are written (the inspection reads the printer model and nozzle) but never listed as changed.
    for (const machine of ["retraction_length", "cooling_tube_length", "parking_pos_retraction", "nozzle_diameter", "printer_model"]) expect(listed).not.toContain(machine);
    expect(settings.retraction_length).toEqual(["0.7"]);
    expect(listed).toEqual([...listed].sort());
  });

  it("takes the filament colors PrusaSlicer shows: the extruder colors when they're set and differ", () => {
    const { settings, warnings } = convertPrusaSettings(
      ini(['filament_colour = #FF8000;#FF8000;#FF8000', 'extruder_colour = #FD8008;"";#191919', "filament_type = PLA;PET;NYLON", "filament_settings_id = \"A\";\"B; b\";\"C\"", "filament_vendor = Prusa Polymers"]),
    );
    expect(settings.filament_colour).toEqual(["#FD8008", "#FF8000", "#191919"]);
    expect(settings.filament_type).toEqual(["PLA", "PETG", "PA"]);
    expect(settings.filament_settings_id).toEqual(["A", "B; b", "C"]);
    // One vendor for every filament, as PrusaSlicer keeps it, spread over the three.
    expect(settings.filament_vendor).toEqual(["Prusa Polymers", "Prusa Polymers", "Prusa Polymers"]);
    expect(settings.different_settings_to_system).toHaveLength(5);
    // The purge arrays Snapmaker Orca sizes by: PrusaSlicer's matrix, and a vector it doesn't have.
    expect(settings.flush_volumes_matrix).toHaveLength(9);
    expect(settings.flush_volumes_vector).toEqual(Array(6).fill("140"));
    expect((settings.different_settings_to_system as string[])[0]).not.toContain("flush_volumes");
    expect(warnings).toEqual(["  note: 2 filament color(s) taken from the printer's extruder colors, which are what PrusaSlicer shows for this project."]);
  });

  it("resolves percentages the way PrusaSlicer does, and leaves alone what Snapmaker Orca can't take", () => {
    const { settings, warnings, dropped } = convertPrusaSettings(
      ini([
        "layer_height = 0.3",
        "first_layer_height = 50%",
        "perimeter_speed = 100",
        "external_perimeter_speed = 50%",
        "infill_speed = 80",
        "solid_infill_speed = 50%",
        "top_solid_infill_speed = 50%",
        "support_material_speed = 60",
        "support_material_interface_speed = 150%",
        "first_layer_speed = 30%",
        "first_layer_infill_speed = 200%",
        "infill_overlap = 0.1",
        "min_bead_width = 85%",
        "fill_pattern = stars",
        "support_material_threshold = 0",
        "support_material_contact_distance = 0.15",
        "support_material_bottom_contact_distance = 0",
        "ironing = 1",
        "ironing_type = topmost",
        "support_material_style = organic",
        "support_material_auto = 1",
        "complete_objects = 1",
        "external_perimeters_first = 1",
        "gap_fill_enabled = 0",
        "infill_every_layers = 3",
        "arc_fitting = disabled",
        "top_one_perimeter_type = topmost",
        "travel_ramping_lift = 0,1",
        "filament_shrinkage_compensation_xy = 0,1.5%",
        "seam_position = rear",
        "draft_shield = limited",
        "filament_retract_length = nil,0.5",
      ]),
    );
    expect(settings.initial_layer_print_height).toBe("0.15");
    expect(settings.outer_wall_speed).toBe("50");
    expect(settings.internal_solid_infill_speed).toBe("40");
    expect(settings.top_surface_speed).toBe("20");
    expect(settings.support_interface_speed).toBe("90");
    expect(settings.initial_layer_speed).toBe("30");
    expect(settings.initial_layer_infill_speed).toBe("60");
    expect(settings.infill_wall_overlap).toBeUndefined();
    expect(settings.min_bead_width).toBe("85%");
    expect(settings.sparse_infill_pattern).toBeUndefined();
    expect(settings.support_threshold_angle).toBeUndefined();
    expect(settings.support_bottom_z_distance).toBe("0.15");
    expect(settings.ironing_type).toBe("topmost");
    expect(settings.support_type).toBe("tree(auto)");
    expect(settings.support_style).toBe("organic");
    expect(settings.print_sequence).toBe("by object");
    expect(settings.wall_sequence).toBe("outer wall/inner wall");
    expect(settings.gap_fill_target).toBe("nowhere");
    expect(settings.infill_combination).toBe("1");
    expect(settings.enable_arc_fitting).toBe("0");
    expect(settings.only_one_wall_top).toBe("1");
    expect(settings.z_hop_types).toEqual(["Normal Lift", "Slope Lift"]);
    expect(settings.filament_shrink).toEqual(["100%", "98.5%"]);
    expect(settings.seam_position).toBe("back");
    expect(settings.draft_shield).toBe("enabled");
    expect(settings.filament_retraction_length).toEqual(["nil", "0.5"]);
    expect(dropped).toContainEqual({ key: "support_material_threshold", why: "automatic overhang detection has no Snapmaker Orca counterpart" });
    expect(warnings).toEqual([
      '  WARN: infill_overlap is 0.1 mm, and Snapmaker Orca keeps it as a percentage of the line width, so Snapmaker\'s stock value is used.',
      '  WARN: fill_pattern "stars" has no Snapmaker Orca counterpart, so Snapmaker\'s stock value is used.',
    ]);
  });

  it("keeps a note or a preset name as one text, commas and all", () => {
    const { settings } = convertPrusaSettings(
      ini(['printer_notes = "PRINTER_VENDOR_PRUSA3D\\nPRINTER_MODEL_COREONE, HF"', "print_settings_id = 0.20mm QUALITY, fast @COREONE", 'notes = "a, b; c"', "filament_notes = \"x, y\";\"z\"", "seam_position = aligned"]),
    );
    expect(settings.printer_notes).toBe("PRINTER_VENDOR_PRUSA3D\nPRINTER_MODEL_COREONE, HF");
    expect(settings.print_settings_id).toBe("0.20mm QUALITY, fast @COREONE");
    expect(settings.notes).toBe("a, b; c");
    expect(settings.filament_notes).toEqual(["x, y", "z"]);
    expect(settings.seam_position).toBe("aligned");
  });

  it("leaves a value below Snapmaker Orca's minimum to the stock profile, as PrusaSlicer's 0 for automatic", () => {
    const { settings, dropped } = convertPrusaSettings(ini(["first_layer_speed = 25", "first_layer_infill_speed = 0", "bridge_speed = 0", "perimeter_speed = 150"]));
    expect(settings.initial_layer_infill_speed).toBeUndefined();
    expect(settings.bridge_speed).toBeUndefined();
    expect(settings.inner_wall_speed).toBe("150");
    expect(dropped).toContainEqual({ key: "initial_layer_infill_speed", why: "0 is below Snapmaker Orca's minimum of 1" });
  });

  it("maps the six settings the lineage research confirmed", () => {
    const { settings } = convertPrusaSettings(
      ini(["fan_always_on = 1,0", "automatic_infill_combination = 1", "infill_every_layers = 1", "automatic_infill_combination_max_layer_height = 100%", "solid_infill_every_layers = 5", "prefer_clockwise_movements = 1", "support_material_synchronize_layers = 1", "filament_travel_ramping_lift = nil,1,0"]),
    );
    expect(settings.reduce_fan_stop_start_freq).toEqual(["1", "0"]);
    expect(settings.infill_combination).toBe("1");
    expect(settings.infill_combination_max_layer_height).toBe("100%");
    expect(settings.extra_solid_infills).toBe("5");
    expect(settings.wall_direction).toBe("cw");
    expect(settings.independent_support_layer_height).toBe("0");
    expect(settings.filament_z_hop_types).toEqual(["nil", "Slope Lift", "Normal Lift"]);
    const off = convertPrusaSettings(ini(["automatic_infill_combination = 0", "infill_every_layers = 1", "solid_infill_every_layers = 0", "prefer_clockwise_movements = 0", "support_material_synchronize_layers = 0", "filament_travel_ramping_lift = nil"])).settings;
    expect(off.infill_combination).toBe("0");
    expect(off.extra_solid_infills).toBeUndefined();
    expect(off.wall_direction).toBeUndefined();
    expect(off.independent_support_layer_height).toBe("1");
    expect(off.filament_z_hop_types).toBeUndefined();
  });

  it("reports keys it has no rule for instead of passing them through", () => {
    const { settings, unknown } = convertPrusaSettings(ini(["some_future_key = 1", "perimeters = 3"]));
    expect(unknown).toEqual(["some_future_key"]);
    expect(settings.some_future_key).toBeUndefined();
    expect(settings.wall_loops).toBe("3");
  });

  it("knows PrusaSlicer 2.9.7's one new key, a printer setting the U1 keeps its own value for", () => {
    const { settings, unknown } = convertPrusaSettings(ini(["used_filament_compensation = 1.05"]));
    expect(unknown).toEqual([]);
    expect(settings.used_filament_compensation).toBeUndefined();
  });

  it("turns PrusaSlicer's unchecked Brim box (a width of 0) into no brim, whatever the type says", () => {
    // Unchecked: PrusaSlicer keeps the type and prints nothing.
    expect(convertPrusaSettings(ini(["brim_type = outer_only", "brim_width = 0"])).settings.brim_type).toBe("no_brim");
    expect(convertPrusaSettings(ini(["brim_type = outer_and_inner", "brim_width = 0.0"])).settings.brim_type).toBe("no_brim");
    // Checked: the type stands.
    expect(convertPrusaSettings(ini(["brim_type = outer_only", "brim_width = 5"])).settings.brim_type).toBe("outer_only");
    expect(convertPrusaSettings(ini(["brim_type = inner_only", "brim_width = 3"])).settings.brim_type).toBe("inner_only");
    expect(convertPrusaSettings(ini(["brim_type = no_brim", "brim_width = 5"])).settings.brim_type).toBe("no_brim");
    // A PrusaSlicer old enough to have no brim type: the width alone.
    const old = convertPrusaSettings(ini(["brim_width = 0"]));
    expect(old.settings.brim_type).toBe("no_brim");
    expect(old.targets.get("brim_width")).toEqual(["brim_width", "brim_type"]);
    expect(convertPrusaSettings(ini(["brim_width = 4"])).settings.brim_type).toBeUndefined();
    // The brim type is listed once, under the key it came from.
    expect(convertPrusaSettings(ini(["brim_type = outer_only", "brim_width = 0"])).targets.get("brim_type")).toEqual(["brim_type"]);
  });

  it("gives an object its own brim when its brim width differs from the project's", () => {
    const project = ini(["brim_type = outer_only", "brim_width = 0"]);
    // The project has none; this object turns it on, so it needs the type as well as the width.
    expect(convertObjectOverrides(project, new Map([["brim_width", "5"]]))).toEqual({ brim_width: "5", brim_type: "outer_only" });
    // The project has one; this object turns it off.
    expect(convertObjectOverrides(ini(["brim_type = outer_only", "brim_width = 5"]), new Map([["brim_width", "0"]]))).toEqual({ brim_width: "0", brim_type: "no_brim" });
    // An object that doesn't touch the brim says nothing about it.
    expect(convertObjectOverrides(project, new Map([["perimeters", "4"]]))).toEqual({ wall_loops: "4" });
  });
});
