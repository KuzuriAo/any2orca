import { readFileSync } from "node:fs";
import { unzipSync, zipSync } from "fflate";
import { describe, expect, it } from "vitest";
import { prepareConvertRequest } from "../../archive/zip.js";
import { convert, inspect } from "../../index.js";
import { decodeStamp } from "../../stamp.js";
import { testProfileSource } from "../../test-helpers.js";
import { findSourceReader } from "../index.js";
import { parsePrusaIni } from "./ini.js";
import { adaptPrusaModel, buildModelSettings, convertCustomGcodes, convertLayerHeights, prusaReader } from "./prusa.js";

const dec = new TextDecoder();
const enc = new TextEncoder();
const fixtureBytes = () => new Uint8Array(readFileSync(new URL("../../test-fixtures/other-formats/prusaslicer-2.9.6.3mf", import.meta.url)));
const fixtureEntries = () => unzipSync(fixtureBytes());

describe("the PrusaSlicer reader", () => {
  it("takes a PrusaSlicer project and leaves the Bambu Studio family and PrusaSlicer's relatives alone", () => {
    expect(findSourceReader(fixtureEntries())).toBe(prusaReader);
    const superSlicer = { ...fixtureEntries(), "Metadata/Slic3r_PE.config": enc.encode("; generated by SuperSlicer 2.5.59 on 2024-01-01\n; layer_height = 0.2\n") };
    expect(findSourceReader(superSlicer)).toBeNull();
    expect(() => prepareConvertRequest(zipSync(superSlicer))).toThrow(expect.objectContaining({ code: "unsupported_slicer", slicer: "SuperSlicer" }));
  });

  it("reads the 2.9.6 fixture: settings in Snapmaker Orca's keys, the object on plate 1, Bambu's files in place of PrusaSlicer's", () => {
    const parsed = prepareConvertRequest(fixtureBytes());
    expect(parsed.source).toBe("prusaslicer");
    expect(parsed.request.projectSettings.wall_loops).toBe("2");
    expect(parsed.request.projectSettings.filament_colour).toEqual(["#FFF2EC"]);
    expect(parsed.request.projectSettings.printer_model).toBe("COREONE");
    expect(parsed.request.objects).toEqual([{ id: "1", name: "Shape-Box", plate: 1, bbox: [112.5, 137.5, 97.5, 122.5] }]);
    const names = Object.keys(parsed.zipEntries).sort();
    expect(names).toEqual(["3D/3dmodel.model", "Metadata/model_settings.config", "Metadata/thumbnail.png", "[Content_Types].xml", "_rels/.rels"]);
    const model = dec.decode(parsed.zipEntries["3D/3dmodel.model"]);
    expect(model).toContain('<metadata name="Application">PrusaSlicer-2.9.6</metadata>\n <metadata name="BambuStudio:3mfVersion">1</metadata>');
    expect(model).toContain("<mesh>");
    const modelSettings = dec.decode(parsed.zipEntries["Metadata/model_settings.config"]);
    expect(modelSettings).toContain('<object id="1">\n    <metadata key="name" value="Shape-Box"/>\n    <part id="1" subtype="normal_part">');
    expect(modelSettings).toContain('<metadata key="object_id" value="1"/>');
    expect(parsed.warnings.filter((w) => w.includes("WARN"))).toEqual([]);
    expect(parsed.warnings.some((w) => w.includes("have no Snapmaker Orca counterpart"))).toBe(true);
  });

  it("converts the fixture end to end into a Snapmaker Orca project", async () => {
    const { output, report } = await convert(fixtureBytes(), { profiles: testProfileSource() });
    const entries = unzipSync(output);
    const settings = JSON.parse(dec.decode(entries["Metadata/project_settings.config"])) as Record<string, unknown>;
    expect(settings.printer_model).toBe("Snapmaker U1");
    expect(settings.wall_loops).toBe("2");
    expect(settings.filament_colour).toEqual(["#FFF2EC"]);
    expect(settings.filament_type).toEqual(["ABS"]);
    // Kept per hotend type by the U1 profile (standard, high flow), both from the one PrusaSlicer value.
    expect(settings.nozzle_temperature).toEqual(["260", "260"]);
    expect(settings.sparse_infill_pattern).toBe("grid");
    expect(settings.sparse_infill_density).toBe("15%");
    const model = dec.decode(entries["3D/3dmodel.model"]);
    expect(model).toMatch(/<metadata name="Application">Snapmaker_Orca-\d/);
    expect(model).toContain('<metadata name="BambuStudio:3mfVersion">1</metadata>');
    expect(Object.keys(entries).some((n) => /Slic3r_PE|Prusa_Slicer/.test(n))).toBe(false);
    expect(decodeStamp(entries["Metadata/any2orca.json"])?.source).toEqual({ format: "prusaslicer", slicerVersion: "2.9.6" });
    expect(report.filaments).toEqual([{ slot: 1, color: "#FFF2EC", type: "ABS", sourceName: "Generic ABS @COREONE HF0.4", outputName: expect.any(String) }]);
    const info = inspect(fixtureBytes());
    expect(info.sourceVendor).toBe("prusa");
    expect(info.slicerVersion).toBe("2.9.6");
    expect(info.printerModel).toBe("COREONE");
  });

  it("keeps every filament of a multi-filament project, with the purge arrays sized to them", async () => {
    const entries = fixtureEntries();
    const ini = dec
      .decode(entries["Metadata/Slic3r_PE.config"])
      .replace(/^; filament_colour = .*$/m, "; filament_colour = #FFF2EC;#102030;#405060")
      .replace(/^; extruder_colour = .*$/m, '; extruder_colour = "";"";""')
      .replace(/^; filament_settings_id = .*$/m, '; filament_settings_id = "Generic ABS @COREONE HF0.4";"Generic PLA @COREONE HF0.4";"Generic PETG @COREONE HF0.4"')
      .replace(/^; filament_type = .*$/m, "; filament_type = ABS;PLA;PET")
      .replace(/^; temperature = .*$/m, "; temperature = 260,215,240")
      .replace(/^; wiping_volumes_matrix = .*$/m, "; wiping_volumes_matrix = 0,140,140,140,0,140,140,140,0");
    entries["Metadata/Slic3r_PE.config"] = enc.encode(ini);
    const { output, report } = await convert(zipSync(entries), { profiles: testProfileSource() });
    const settings = JSON.parse(dec.decode(unzipSync(output)["Metadata/project_settings.config"])) as Record<string, unknown>;
    expect(settings.filament_colour).toEqual(["#FFF2EC", "#102030", "#405060"]);
    expect(settings.filament_type).toEqual(["ABS", "PLA", "PETG"]);
    expect(settings.flush_volumes_matrix).toHaveLength(9);
    expect(settings.flush_volumes_vector).toHaveLength(6);
    expect(report.filaments.map((f) => [f.slot, f.color, f.type])).toEqual([
      [1, "#FFF2EC", "ABS"],
      [2, "#102030", "PLA"],
      [3, "#405060", "PETG"],
    ]);
  });

  it("carries painting, color changes, layer heights and instances, and says what a multi-part object loses", () => {
    const entries = fixtureEntries();
    const model = dec
      .decode(entries["3D/3dmodel.model"])
      .replace('<triangle v1="4" v2="6" v3="7"/>', '<triangle v1="4" v2="6" v3="7" slic3rpe:mmu_segmentation="8" slic3rpe:custom_seam="4" slic3rpe:custom_supports="C"/>')
      .replace('<item objectid="1" transform="1 0 0 0 1 0 0 0 1 125 110 12.5" printable="1"/>', '<item objectid="1" transform="1 0 0 0 1 0 0 0 1 125 110 12.5" printable="1"/>\n  <item objectid="1" transform="1 0 0 0 1 0 0 0 1 25 10 12.5" printable="1"/>');
    entries["3D/3dmodel.model"] = enc.encode(model);
    entries["Metadata/Slic3r_PE_model.config"] = enc.encode(`<?xml version="1.0" encoding="UTF-8"?>
<config>
 <object id="1" instances_count="2">
  <metadata type="object" key="name" value="Two &amp; parts"/>
  <metadata type="object" key="perimeters" value="4"/>
  <metadata type="object" key="fill_density" value="40%"/>
  <volume firstid="0" lastid="5">
   <metadata type="volume" key="name" value="a"/>
   <metadata type="volume" key="volume_type" value="ModelPart"/>
   <metadata type="volume" key="extruder" value="2"/>
  </volume>
  <volume firstid="6" lastid="11">
   <metadata type="volume" key="name" value="b"/>
   <metadata type="volume" key="volume_type" value="ModelPart"/>
   <metadata type="volume" key="extruder" value="3"/>
  </volume>
 </object>
</config>`);
    entries["Metadata/Prusa_Slicer_custom_gcode_per_print_z.xml"] = enc.encode(`<?xml version="1.0" encoding="utf-8"?>
<custom_gcodes_per_print_z>
<code print_z="17.79" type="0" extruder="1" color="#FFFF00" extra="" gcode="M600
G1 E0.4 F1500"/>
<code print_z="20" type="1" extruder="1" color="" extra="" gcode="M601"/>
<code print_z="21.5" type="4" extruder="1" color="" extra="M117 hi &amp; bye" gcode="M117 hi &amp; bye"/>
<code print_z="bad" type="0" extruder="1" color="" extra="" gcode=""/>
<mode value="MultiAsSingle"/>
</custom_gcodes_per_print_z>`);
    entries["Metadata/Slic3r_PE_layer_heights_profile.txt"] = enc.encode("object_id=1|0.000000;0.200000;6.076239;0.200000;6.176239;0.199050\nobject_id=2|0;0.1\n");
    entries["Metadata/Prusa_Slicer_wipe_tower_information.xml"] = enc.encode("<wipe_tower_information/>");

    const parsed = prepareConvertRequest(zipSync(entries));
    const out = dec.decode(parsed.zipEntries["3D/3dmodel.model"]);
    expect(out).toContain('<triangle v1="4" v2="6" v3="7" paint_color="8" paint_seam="4" paint_supports="C"/>');
    expect(out).not.toContain("slic3rpe:mmu_segmentation");
    expect(dec.decode(parsed.zipEntries["Metadata/custom_gcode_per_layer.xml"])).toBe(
      [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<custom_gcodes_per_layer>",
        "<plate>",
        '<plate_info id="1"/>',
        '<layer top_z="17.79" type="0" extruder="1" color="#FFFF00" extra="" gcode=""/>',
        '<layer top_z="20" type="1" extruder="1" color="" extra="" gcode=""/>',
        '<layer top_z="21.5" type="4" extruder="1" color="" extra="M117 hi &amp; bye" gcode="M117 hi &amp; bye"/>',
        '<mode value="MultiAsSingle"/>',
        "</plate>",
        "</custom_gcodes_per_layer>",
        "",
      ].join("\n"),
    );
    expect(dec.decode(parsed.zipEntries["Metadata/layer_heights_profile.txt"])).toBe("layer_heights_profile_format_version=2\nobject_id=1|0.000000;0.200000;6.076239;0.200000;6.176239;0.199050\n");
    expect(parsed.zipEntries["Metadata/Prusa_Slicer_wipe_tower_information.xml"]).toBeUndefined();
    const modelSettings = dec.decode(parsed.zipEntries["Metadata/model_settings.config"]);
    expect(modelSettings).toContain('<metadata key="name" value="Two &amp; parts"/>');
    expect(modelSettings).toContain('<metadata key="sparse_infill_density" value="40%"/>');
    expect(modelSettings).toContain('<metadata key="wall_loops" value="4"/>');
    expect(modelSettings).not.toContain('key="extruder"');
    expect((modelSettings.match(/<model_instance>/g) ?? []).length).toBe(2);
    expect(modelSettings).toContain('<metadata key="instance_id" value="1"/>');
    expect(parsed.request.objects.map((o) => o.name)).toEqual(["Two & parts"]);
    expect(parsed.warnings).toContainEqual(
      '  WARN: "Two & parts" is 2 parts in PrusaSlicer, converted as one part on filament 1; not carried: the parts on filament 2, 3. Split the parts into separate objects in PrusaSlicer to keep them.',
    );
  });

  it("builds the model settings for an object with its own filament and a modifier", () => {
    const ini = parsePrusaIni("; generated by PrusaSlicer 2.9.6 on x\n; layer_height = 0.2\n");
    const warnings: string[] = [];
    const xml = buildModelSettings(
      ini,
      [
        {
          id: 7,
          name: "Cone",
          extruder: 3,
          settings: new Map(),
          volumes: [
            { firstTriangle: 0, lastTriangle: 9, volumeType: "ModelPart", extruder: 0, name: "Cone", settings: new Map() },
            { firstTriangle: 10, lastTriangle: 11, volumeType: "ParameterModifier", extruder: 0, name: "dense", settings: new Map([["fill_density", "80%"]]) },
          ],
        },
      ],
      new Map([[7, 1]]),
      warnings,
    );
    expect(xml).toContain('<object id="7">\n    <metadata key="name" value="Cone"/>\n    <metadata key="extruder" value="3"/>');
    expect(warnings).toEqual(['  WARN: "Cone" is 2 parts in PrusaSlicer, converted as one part on filament 3; not carried: 1 modifier (ParameterModifier). Split the parts into separate objects in PrusaSlicer to keep them.']);
  });

  it("adapts a model without an Application line, and leaves one that already has the version entry alone", () => {
    const adapted = adaptPrusaModel('<model unit="millimeter">\n <resources/>\n</model>');
    expect(adapted.text).toBe('<model unit="millimeter">\n <metadata name="BambuStudio:3mfVersion">1</metadata>\n <resources/>\n</model>');
    expect(adapted.painted).toBe(false);
    const native = '<model>\n <metadata name="BambuStudio:3mfVersion">1</metadata>\n</model>';
    expect(adaptPrusaModel(native).text).toBe(native);
  });

  it("gives nothing for color changes or layer heights that aren't there", () => {
    expect(convertCustomGcodes("<custom_gcodes_per_print_z></custom_gcodes_per_print_z>")).toBeNull();
    expect(convertCustomGcodes("<html>")).toBeNull();
    expect(convertLayerHeights("garbage\n", [1])).toBeNull();
    expect(convertLayerHeights("object_id=3|0;0.2\n", [1, 2])).toBeNull();
  });
});
