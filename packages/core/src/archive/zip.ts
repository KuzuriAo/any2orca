import { zipSync } from "fflate";
import { Any2orcaError } from "../errors.js";
import type { ConvertResponse } from "../schema.js";
import { findSourceReader, type ParsedProject } from "../sources/index.js";
import { adaptModelSettings } from "./adaptModelSettings.js";
import { setApplicationMetadata } from "./setApplicationMetadata.js";
import { MODEL_SETTINGS_PATH, PROJECT_SETTINGS_PATH, SPECIAL_HANDLING, TOP_MODEL_PATH } from "./paths.js";
import { recenterAssembleItems } from "./recenterAssembleItems.js";
import { recenterBuildItems } from "./recenterBuildItems.js";
import { formatSize, LARGE_PROJECT_BYTES, safeUnzipSync } from "./safeUnzip.js";
import { shouldDropFromBambu } from "./shouldDropFromBambu.js";

const utf8Decoder = new TextDecoder("utf-8");
const utf8Encoder = new TextEncoder();

/** Where PrusaSlicer and the slicers built on it keep a project's print settings. */
const OTHER_FORMAT_SETTINGS_PATH = "Metadata/Slic3r_PE.config";

/**
 * The slicer an other-format project names on its first line ("; generated by PrusaSlicer 2.9.1 on ..."),
 * for the message. The file is untrusted: only a short plain name is used, from the first 200 bytes.
 */
function otherFormatSlicer(settings: Uint8Array): string {
  const firstLine = utf8Decoder.decode(settings.subarray(0, 200)).split(/\r?\n/, 1)[0] ?? "";
  const name = /^; generated by ([A-Za-z][A-Za-z0-9]{1,30}(?: [A-Za-z][A-Za-z0-9]{1,30})?) v?\d/.exec(firstLine)?.[1];
  return name ?? "PrusaSlicer or a slicer based on it";
}

/**
 * Unzips a source .3mf (already in memory as bytes), refuses what no reader converts, and hands the entries to
 * the reader that recognizes them (`sources/`): the conversion request is the project's settings in Snapmaker
 * Orca's keys, plus each top-level object's world-space bounding box (or its raw transform translation as a
 * fallback when mesh geometry is missing), its plate assignment, and its name.
 */
export function prepareConvertRequest(fileBytes: Uint8Array, maxUnpackedBytes?: number): ParsedProject {
  const zipEntries = safeUnzipSync(fileBytes, maxUnpackedBytes);
  const warnings: string[] = [];
  const unpackedBytes = Object.values(zipEntries).reduce((n, bytes) => n + bytes.length, 0);
  if (unpackedBytes > LARGE_PROJECT_BYTES) {
    warnings.push(
      `  WARN: This is a large project (${formatSize(unpackedBytes)} unpacked). Converting it takes a minute or two and a few GB of memory; close other apps or tabs if your computer has little memory.`,
    );
  }

  // A sliced plate file (.gcode.3mf) holds G-code for the printer it was sliced for and usually no model; a
  // converted copy would carry that G-code into a file labeled for the U1.
  if (Object.keys(zipEntries).some((name) => /^Metadata\/plate_\d+\.gcode$/i.test(name))) {
    throw new Any2orcaError(
      "invalid_project",
      "This is a sliced plate file (.gcode.3mf): it holds G-code for the printer it was sliced for, not a project to convert. Convert the project file it was sliced from instead.",
    );
  }

  const reader = findSourceReader(zipEntries);
  if (reader) return reader.read(zipEntries, { unpackedBytes, warnings });

  // No reader knows this file. Say which kind of file it is.
  // The slicers built on PrusaSlicer (SuperSlicer, an older AnycubicSlicer) keep their print settings in
  // PrusaSlicer's file and format, with keys of their own: a project, but not one this converts.
  const otherFormatSettings = zipEntries[OTHER_FORMAT_SETTINGS_PATH];
  if (otherFormatSettings) {
    const slicer = otherFormatSlicer(otherFormatSettings);
    throw new Any2orcaError(
      "unsupported_slicer",
      `This project was saved by ${slicer}, and only projects from Bambu Studio, Creality Print, Anycubic Slicer Next, ElegooSlicer, Flash Studio and PrusaSlicer can be converted.`,
      { slicer },
    );
  }
  // A zip that isn't a 3MF at all (no model part, no print settings): a bundle of STL files, say.
  if (!zipEntries[TOP_MODEL_PATH]) {
    throw new Any2orcaError(
      "invalid_file",
      "This file is a zip, but not a 3MF project, and holds no 3MF to convert. Model files such as STLs don't need converting: open them in Snapmaker Orca and choose a U1 profile.",
    );
  }
  throw new Any2orcaError(
    "invalid_file",
    "This 3MF holds only the model, with no print settings, so there's nothing to convert: open it in Snapmaker Orca and choose a U1 profile.",
  );
}

/**
 * Apply a conversion response to the originally parsed project and
 * produce the final Snapmaker Orca .3mf bytes, ready to offer as a
 * download. Copies every untouched zip entry verbatim (dropping
 * Bambu-only files per shouldDropFromBambu), sets the Application line (or, when
 * the catalog names none, adds the OrcaSlicer origin tag), recenters the build/assemble transforms using the
 * response's shift map, adapts model_settings.config, and writes the
 * response's merged project_settings.config plus every generated/
 * passthrough config file. `extraEntries` are added last (the output stamp).
 */
export function applyConvertResponse(
  parsed: ParsedProject,
  response: ConvertResponse,
  extraEntries: Record<string, Uint8Array> = {},
): Uint8Array {
  const { zipEntries, warnings } = parsed;
  const outputEntries: Record<string, Uint8Array> = {};

  for (const [name, data] of Object.entries(zipEntries)) {
    if (shouldDropFromBambu(name) || SPECIAL_HANDLING.has(name)) continue;
    outputEntries[name] = data;
  }

  const modelSettingsBytes = zipEntries[MODEL_SETTINGS_PATH];
  if (modelSettingsBytes) {
    const adapted = adaptModelSettings(utf8Decoder.decode(modelSettingsBytes));
    const recentered = recenterAssembleItems(adapted, response.shifts, warnings);
    outputEntries[MODEL_SETTINGS_PATH] = utf8Encoder.encode(recentered);
  }

  const topModelBytes = zipEntries[TOP_MODEL_PATH];
  if (topModelBytes) {
    // The target slicer's own Application value, so the file says what a save in that release says.
    const text = utf8Decoder.decode(topModelBytes);
    const tagged = setApplicationMetadata(text, response.application);
    const recentered = recenterBuildItems(tagged, response.shifts, warnings);
    outputEntries[TOP_MODEL_PATH] = utf8Encoder.encode(recentered);
  }

  for (const [arcname, config] of Object.entries(response.configFiles)) {
    outputEntries[arcname] = utf8Encoder.encode(JSON.stringify(config, null, 4));
  }

  outputEntries[PROJECT_SETTINGS_PATH] = utf8Encoder.encode(JSON.stringify(response.projectSettings, null, 4));

  for (const [arcname, data] of Object.entries(extraEntries)) {
    outputEntries[arcname] = data;
  }

  // A fixed entry time, so the same input and options always give the same
  // bytes (stable checksums in a publish step), and a converted file doesn't
  // record when, or in which time zone, it was converted. Zip times are local
  // clock fields, so a Date built from local fields encodes identically everywhere.
  //
  // Level 3: on a sample of 192 real projects, it wrote in 51% of level 6's time for
  // files 1.7% larger (level 2: 46% and 2.6%; level 1: 41% and 4.4%), so going lower
  // buys little time for more size. A 1.4 GB project spent about 50 s of a 75 s
  // conversion compressing at level 6. Every entry's content is the same at any
  // level; only the zip's bytes differ, and Snapmaker Orca opens the files the same way.
  return zipSync(outputEntries, { level: OUTPUT_DEFLATE_LEVEL, mtime: FIXED_ENTRY_TIME });
}
/** The output's deflate level; exported for the test that holds it. */
export const OUTPUT_DEFLATE_LEVEL = 3;

const FIXED_ENTRY_TIME = new Date(2000, 0, 1, 0, 0, 0);
